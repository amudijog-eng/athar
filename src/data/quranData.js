// Helper function to build Audio URL for a Surah with selected reciter
export const getSurahAudioUrl = (reciterServer, surahId) => {
  const formattedId = String(surahId).padStart(3, '0');
  return `${reciterServer}${formattedId}.mp3`;
};

// Helper function for verse-by-verse EveryAyah CDN
export const getAyahAudioUrl = (reciterFolder, surahId, ayahId) => {
  // standard everyayah format: e.g. https://everyayah.com/data/Alafasy_128kbps/001001.mp3
  const s = String(surahId).padStart(3, '0');
  const a = String(ayahId).padStart(3, '0');
  return `https://everyayah.com/data/Alafasy_128kbps/${s}${a}.mp3`;
};
